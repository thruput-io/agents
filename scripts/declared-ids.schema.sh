#!/usr/bin/env bash
set -euo pipefail

ids=$(grep -h '^- id: ' "$PROJECT_ROOT"/rules/*.yaml | sed 's/^- id: //')
enumeration=$(printf '%s\n' "$ids" | sed 's/["\\]/\\&/g; s/.*/"&"/' | paste -sd, -)
alternation=$(printf '%s\n' "$ids" | sed 's/[][\\.^$*+?(){}|]/\\&/g; s/\\/\\\\/g' | paste -sd'|' -)
definitions=$(grep '^- id: ' "$PROJECT_ROOT/rules/Definitions.yaml" | sed 's/^- id: //')
definition_alternation=$(printf '%s\n' "$definitions" | sed 's/[][\\.^$*+?(){}|]/\\&/g; s/\\/\\\\/g' | paste -sd'|' -)

cat <<JSON
{
  "\$schema": "https://json-schema.org/draft/2020-12/schema",
  "\$id": "https://thruput.se/agents/schemas/governance/declared-ids.g.schema.json",
  "title": "Declared ids",
  "description": "Generated by scripts/declared-ids.schema.sh from every id declared in rules/: the governance schema with the Id, References, and CitedDefinition dynamic anchors bound to their enumeration",
  "\$ref": "https://thruput.se/agents/schemas/governance/governance.schema.json",
  "\$defs": {
    "Id": {
      "\$dynamicAnchor": "Id",
      "enum": [$enumeration]
    },
    "References": {
      "\$dynamicAnchor": "References",
      "pattern": "^[^\\\\[]*(?:(?:\\\\[\\\\[(?:$alternation)\\\\]\\\\]|\\\\[[^\\\\[])[^\\\\[]*)*\\\\[?\$"
    },
    "CitedDefinition": {
      "\$dynamicAnchor": "CitedDefinition",
      "pattern": "\\\\[\\\\[(?:$definition_alternation)\\\\]\\\\]"
    }
  },
  "examples": [
    {
      "axioms": []
    }
  ]
}
JSON
