#!/usr/bin/env bash
set -euo pipefail

echo 'start'

out=${1:?usage: bundle-schemas.sh <output-dir>}
base=https://thruput.se/agents/schemas
schemas="$PROJECT_ROOT/schemas"
tmp=build/bundle
mkdir -p $tmp

jsonschema=(npx --yes @sourcemeta/jsonschema@17.0.0)

bundle() {
  local dir=$1 title=$2 id=$3
  local refs
  refs=$(cd "$schemas" && find "$dir" -name '*.schema.json' ! -name '*.g.*' | sort \
    | sed "s#^\./##; s#.*#{\"\$ref\": \"$base/&\"}#" | paste -sd, -)
  local index
  index="$tmp/$(printf '%s' "$dir" | tr / -).index.json"
  cat > "$index" <<JSON
{
  "\$schema": "https://json-schema.org/draft/2020-12/schema",
  "\$id": "$id",
  "title": "$title",
  "description": "Generated by scripts/bundle-schemas.sh: every schema in $dir, bundled into one self-contained document",
  "anyOf": [$refs]
}
JSON
  mkdir -p "$out/$dir"
  "${jsonschema[@]}" bundle "$index" --resolve "$schemas" > "$out/$dir/bundle.g.schema.json"
}

for folder in "$schemas"/*/; do
  name=$(basename "$folder")
  bundle "$name" "Bundle of $name schemas" "$base/$name/bundle.g.schema.json"
done

echo 'soon'

bundle . "Bundle of all schemas" "$base/bundle.g.schema.json"

echo 'done'
